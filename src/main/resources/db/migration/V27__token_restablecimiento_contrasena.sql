-- =============================================================================
-- V27 - Tokens para restablecer la contrasena
-- =============================================================================
-- Cada fila es un enlace de un solo uso enviado por correo al usuario que
-- olvido su contrasena. Se guarda el hash SHA-256 del token (64 caracteres
-- hexadecimales), nunca el token en si: quien lea la tabla no puede armar un
-- enlace valido.
--
--   fecha_expiracion  momento a partir del cual el enlace deja de servir
--   fecha_uso         momento en que se restablecio la contrasena con el enlace;
--                     NULL mientras no se uso
--   created_date      momento en que se envio el enlace; acota cada cuanto se
--                     le puede enviar otro al mismo usuario
--
-- La bitacora de auditoria admite las acciones de solicitud y de
-- restablecimiento de la contrasena.
-- =============================================================================

create table token_restablecimiento_contrasena (
    id bigint generated by default as identity,
    usuario_id bigint not null,
    token_hash varchar(64) not null,
    fecha_expiracion timestamp(6) not null,
    fecha_uso timestamp(6),
    created_date timestamp(6),
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_token_restablecimiento_contrasena primary key (id),
    constraint uk_token_restablecimiento_contrasena_token_hash unique (token_hash)
);

alter table if exists token_restablecimiento_contrasena
    add constraint fk_token_restablecimiento_contrasena_usuario_id foreign key (usuario_id) references usuarios (id);

CREATE INDEX IF NOT EXISTS idx_token_restablecimiento_contrasena_usuario_id_created_date
    ON token_restablecimiento_contrasena (usuario_id, created_date);

ALTER TABLE audit_log DROP CONSTRAINT ck_audit_log_accion;

ALTER TABLE audit_log ADD CONSTRAINT ck_audit_log_accion CHECK (accion IN ('CREAR','MODIFICAR','ELIMINAR','ANULAR','FINALIZAR','LOGIN_EXITOSO','LOGOUT','SOLICITUD_RESTABLECIMIENTO_CONTRASENA','RESTABLECIMIENTO_CONTRASENA'));
