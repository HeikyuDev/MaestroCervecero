-- =============================================================================
-- V8 - Escalado del lote
-- =============================================================================
-- Al iniciar un lote se guarda una instantanea de los datos con los que se
-- escalo, para que sus cantidades no cambien si despues se modifican los
-- equipos o los insumos:
--
-- - escalado_lote: los parametros de los cuatro equipos del lote (molino,
--   macerador, olla de hervor y fermentador). Cada lote tiene como maximo uno,
--   referenciado desde lote.escalado_lote_id.
-- - escalado_lote_insumo: los parametros de cada insumo de la receta del lote
--   (extracto potencial de la malta, acidos alfa y formato del lupulo, tipo y
--   celulas por gramo de la levadura).
--
-- Los lotes iniciados antes de esta migracion no tienen escalado_lote_id: su
-- escalado se calcula con los valores vigentes de los equipos e insumos.
-- =============================================================================

create table escalado_lote (
    id bigint generated by default as identity,
    capacidad_util_fermentador double precision not null,
    capacidad_util_macerador double precision not null,
    capacidad_util_olla double precision not null,
    created_date timestamp(6),
    eficiencia_maceracion double precision not null,
    espacio_muerto_macerador double precision not null,
    evaporacion_olla double precision not null,
    last_modified_date timestamp(6),
    perdida_por_trub_olla double precision not null,
    rendimiento_molienda double precision not null,
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_escalado_lote primary key (id)
);

create table escalado_lote_insumo (
    id bigint generated by default as identity,
    alfa_acidos double precision,
    cantidad_celulas_por_gramo double precision,
    created_date timestamp(6),
    escalado_lote_id bigint not null,
    insumo_id bigint not null,
    last_modified_date timestamp(6),
    potencial_extracto double precision,
    created_by varchar(255),
    formato varchar(255),
    last_modified_by varchar(255),
    tipo_levadura varchar(255),
    constraint pk_escalado_lote_insumo primary key (id),
    constraint fk_escalado_lote_insumo_escalado_lote foreign key (escalado_lote_id) references escalado_lote (id),
    constraint fk_escalado_lote_insumo_insumo foreign key (insumo_id) references insumo (id),
    constraint ck_escalado_lote_insumo_formato check (formato is null or formato in ('PELLET','FLOR')),
    constraint ck_escalado_lote_insumo_tipo_levadura check (tipo_levadura is null or tipo_levadura in ('ALE','HIBRIDA','LAGER'))
);

create unique index udx_escalado_lote_insumo_escalado_insumo on escalado_lote_insumo (escalado_lote_id, insumo_id);

alter table lote add column escalado_lote_id bigint;
alter table lote add constraint uk_lote_escalado_lote unique (escalado_lote_id);
alter table lote add constraint fk_lote_escalado_lote foreign key (escalado_lote_id) references escalado_lote (id);
