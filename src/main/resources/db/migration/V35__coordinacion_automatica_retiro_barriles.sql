ALTER TABLE audit_log ADD CONSTRAINT ck_audit_log_concepto_auditoria CHECK (concepto_auditoria IN ('SESION','MALTA','LUPULO','LEVADURA','MACERADOR','OLLA_DE_HERVOR','MOLINO','FERMENTADOR','RECETA','PLANIFICACION_PRODUCCION','LOTE','CONSUMO_INSUMO','ENVASADO_LOTE','BARRIL','FABRICANTE_BARRIL','FALLA_BARRIL','MANTENIMIENTO_BARRIL','LIMPIEZA_BARRIL','LIMPIEZA_EQUIPAMIENTO','FALLA_EQUIPAMIENTO','MANTENIMIENTO_EQUIPAMIENTO','PRESENTACION_COMERCIAL','PAIS','PROVINCIA','LOCALIDAD','PROVEEDOR','ORDEN_COMPRA','INGRESO_INSUMO','COSTO_DIRECTO_ADICIONAL','COSTO_FIJO','CLIENTE','DESPACHO_BARRIL','DEVOLUCION_BARRIL','FRACCIONAMIENTO_BARRIL','SOLICITUD_BUSQUEDA','CONFIGURACION_PRODUCCION','CONFIGURACION_COMPRAS','CONFIGURACION_DISTRIBUCION','MOTIVO_AJUSTE','AJUSTE_INSUMO','USUARIO'));
