-- =============================================================================
-- V35 - Coordinacion automatica del retiro de barriles
-- =============================================================================
-- Una vez por dia, a la hora configurada, el sistema envia a cada cliente un
-- correo con sus barriles con la devolucion vencida que no tienen una
-- solicitud de busqueda pendiente. El correo lleva un enlace personal (solo se
-- guarda el hash SHA-256 del token) a una pantalla publica donde el cliente
-- propone la fecha y hora del retiro; al confirmarla se registra una solicitud
-- de busqueda por barril y se avisa a los encargados de distribucion. Al
-- registrar la devolucion del barril, su solicitud pendiente queda buscada;
-- al anular el despacho, queda cancelada.
--
--   configuracion_distribucion     fila unica (id = 1) con la hora del envio
--                                  diario y los dias maximos de anticipacion
--                                  del retiro
--   invitacion_retiro_barriles     invitacion diaria de un cliente (una por
--                                  cliente y dia), su enlace y el resultado del
--                                  envio del correo
--   invitacion_retiro_despacho     despachos vencidos que lista la invitacion
--   ejecucion_recordatorios_retiro dias en los que ya se completo el envio
--                                  diario (sobrevive a los reinicios)
--   solicitud_busqueda             estado (PENDIENTE, BUSCADA o CANCELADA) en
--                                  lugar del indicador buscado, invitacion que
--                                  la origino y devolucion que la dio por buscada
--
-- Un despacho tiene a lo sumo una solicitud de busqueda pendiente (si ya habia
-- varias, queda pendiente la mas reciente) y una devolucion da por buscada a lo
-- sumo una solicitud. La bitacora de auditoria
-- admite el concepto de la configuracion de distribucion.
-- =============================================================================

create table configuracion_distribucion (
    id bigint not null,
    hora_envio_recordatorio_retiro time not null,
    dias_maximos_anticipacion_retiro integer not null,
    created_date timestamp(6),
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_configuracion_distribucion primary key (id),
    constraint ck_configuracion_distribucion_id check (id = 1),
    constraint ck_configuracion_distribucion_dias_maximos_anticipacion_retiro check (dias_maximos_anticipacion_retiro >= 1 and dias_maximos_anticipacion_retiro <= 30)
);

insert into configuracion_distribucion (id, hora_envio_recordatorio_retiro, dias_maximos_anticipacion_retiro,
                                        created_date, last_modified_date, created_by, last_modified_by)
values (1, '09:00', 7, current_timestamp, current_timestamp, 'SISTEMA', 'SISTEMA');

create table invitacion_retiro_barriles (
    id bigint generated by default as identity,
    cliente_id bigint not null,
    fecha_invitacion date not null,
    token_hash varchar(64),
    fecha_expiracion timestamp(6) not null,
    estado_envio varchar(255) not null,
    intentos_envio integer not null default 0,
    fecha_ultimo_intento_envio timestamp(6),
    fecha_respuesta timestamp(6),
    created_date timestamp(6),
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_invitacion_retiro_barriles primary key (id),
    constraint uk_invitacion_retiro_barriles_token_hash unique (token_hash),
    constraint uk_invitacion_retiro_barriles_cliente_fecha unique (cliente_id, fecha_invitacion),
    constraint ck_invitacion_retiro_barriles_estado_envio check (estado_envio in ('PENDIENTE','EN_ENVIO','ENVIADA','FALLIDA','OMITIDA')),
    constraint ck_invitacion_retiro_barriles_intentos_envio check (intentos_envio >= 0)
);

create table invitacion_retiro_despacho (
    invitacion_retiro_barriles_id bigint not null,
    despacho_barril_id bigint not null,
    constraint pk_invitacion_retiro_despacho primary key (invitacion_retiro_barriles_id, despacho_barril_id)
);

create table ejecucion_recordatorios_retiro (
    fecha date not null,
    fecha_fin timestamp(6) not null,
    constraint pk_ejecucion_recordatorios_retiro primary key (fecha)
);

alter table solicitud_busqueda add column invitacion_retiro_barriles_id bigint;

alter table solicitud_busqueda add column devolucion_barril_id bigint;

alter table if exists invitacion_retiro_barriles
    add constraint fk_invitacion_retiro_barriles_cliente_id foreign key (cliente_id) references cliente (id);

alter table if exists invitacion_retiro_despacho
    add constraint fk_invitacion_retiro_despacho_invitacion_retiro_barriles_id foreign key (invitacion_retiro_barriles_id) references invitacion_retiro_barriles (id);

alter table if exists invitacion_retiro_despacho
    add constraint fk_invitacion_retiro_despacho_despacho_barril_id foreign key (despacho_barril_id) references despacho_barril (id);

alter table if exists solicitud_busqueda
    add constraint fk_solicitud_busqueda_invitacion_retiro_barriles_id foreign key (invitacion_retiro_barriles_id) references invitacion_retiro_barriles (id);

alter table if exists solicitud_busqueda
    add constraint fk_solicitud_busqueda_devolucion_barril_id foreign key (devolucion_barril_id) references devolucion_barril (id);

-- Antes de exigir una sola solicitud pendiente por despacho se consolidan los
-- datos existentes: de las pendientes de un mismo despacho queda pendiente la
-- mas reciente (mayor id) y las demas quedan buscadas
UPDATE solicitud_busqueda s SET buscado = true
WHERE s.buscado = false
  AND EXISTS (SELECT 1 FROM solicitud_busqueda o
              WHERE o.despacho_barril_id = s.despacho_barril_id AND o.buscado = false AND o.id > s.id);

-- El indicador buscado se reemplaza por el estado de la solicitud: buscada
-- (true) pasa a BUSCADA y pendiente (false) a PENDIENTE
ALTER TABLE solicitud_busqueda ADD COLUMN estado varchar(255);

UPDATE solicitud_busqueda SET estado = CASE WHEN buscado THEN 'BUSCADA' ELSE 'PENDIENTE' END;

ALTER TABLE solicitud_busqueda ALTER COLUMN estado SET NOT NULL;

ALTER TABLE solicitud_busqueda ADD CONSTRAINT ck_solicitud_busqueda_estado
    CHECK (estado IN ('PENDIENTE','BUSCADA','CANCELADA'));

ALTER TABLE solicitud_busqueda DROP COLUMN buscado;

-- Una sola solicitud de busqueda pendiente por despacho
CREATE UNIQUE INDEX IF NOT EXISTS udx_solicitud_busqueda_despacho_pendiente
    ON solicitud_busqueda (despacho_barril_id) WHERE estado = 'PENDIENTE';

-- Una devolucion da por buscada a lo sumo una solicitud
CREATE UNIQUE INDEX IF NOT EXISTS udx_solicitud_busqueda_devolucion_barril
    ON solicitud_busqueda (devolucion_barril_id) WHERE devolucion_barril_id IS NOT NULL;

-- La pantalla publica lista las solicitudes de una invitacion
CREATE INDEX IF NOT EXISTS idx_solicitud_busqueda_invitacion_retiro_barriles
    ON solicitud_busqueda (invitacion_retiro_barriles_id);

