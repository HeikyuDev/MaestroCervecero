-- =============================================================================
-- V1 - Esquema inicial
-- =============================================================================
-- Estructura completa de tablas, claves primarias, claves unicas, restricciones
-- de dominio (enumeraciones) y claves foraneas de las entidades JPA.
--
-- Convencion de nombres de restricciones:
--   pk_<tabla>                 clave primaria
--   uk_<tabla>_<columnas>      clave unica
--   ck_<tabla>_<columna>       restriccion de dominio de una enumeracion
--   fk_<tabla>_<columna>       clave foranea
--
-- Las tablas figuran en orden alfabetico y las claves foraneas se declaran al
-- final, de modo que el orden de creacion no depende de las dependencias.
-- =============================================================================

