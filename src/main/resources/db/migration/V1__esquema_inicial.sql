    cantidad_reservada double precision not null,
    etapa_lote_id bigint not null,
    lote_insumo_id bigint not null,
    constraint pk_reserva_insumo primary key (id)
);

create table solicitud_busqueda (
    id bigint generated by default as identity,
    buscado boolean not null,
    created_date timestamp(6),
    despacho_barril_id bigint not null,
    fecha_busqueda timestamp(6) not null,
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    observaciones varchar(255),
    constraint pk_solicitud_busqueda primary key (id)
);

create table usuarios (
    id bigint generated by default as identity,
    account_non_expired boolean not null,
    account_non_locked boolean not null,
    credentials_non_expired boolean not null,
    is_enabled boolean not null,
    created_date timestamp(6),
    last_modified_date timestamp(6),
    apellido varchar(255) not null,
    correo varchar(255) not null,
    created_by varchar(255),
    estado varchar(255) not null,
    last_modified_by varchar(255),
    nombre varchar(255) not null,
    password varchar(255) not null,
    rol varchar(255) not null,
    telefono varchar(255) not null,
    username varchar(255) not null,
    constraint pk_usuarios primary key (id),
    constraint uk_usuarios_username unique (username),
    constraint ck_usuarios_estado check (estado in ('ACTIVO','BAJA')),
    constraint ck_usuarios_rol check (rol in ('GERENTE_DE_PRODUCCION','OPERARIO_DE_PRODUCCION','GERENTE_DE_COMPRAS','ENCARGADO_DE_DEPOSITO','GERENTE_COMERCIAL','ADMINISTRADOR'))
);

create table version_proveedor (
    id bigint generated by default as identity,
    es_ultima_version boolean not null,
    localidad_id bigint not null,
    proveedor_id bigint not null,
    cuit varchar(255) not null,
    direccion varchar(255) not null,
    email varchar(255) not null,
    nombre_comercial varchar(255) not null,
    razon_social varchar(255) not null,
    telefono varchar(255) not null,
    constraint pk_version_proveedor primary key (id)
);

create table version_receta (
    id bigint generated by default as identity,
    duracion_fermentacion integer not null,
    duracion_hervido integer not null,
    duracion_maceracion integer not null,
    duracion_maduracion integer not null,
    es_ultima_version boolean not null,
    fg_objetivo double precision not null,
    ibu_objetivo integer not null,
    og_objetivo double precision not null,
    relacion_de_empaste double precision not null,
    volumen_base double precision not null,
    receta_id bigint not null,
    nombre varchar(255) not null,
    constraint pk_version_receta primary key (id)
);

