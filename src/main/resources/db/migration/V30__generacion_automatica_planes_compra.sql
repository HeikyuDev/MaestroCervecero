-- =============================================================================
-- V30 - Generacion automatica de planes de ordenes de compra
-- =============================================================================
-- Al registrar una planificacion de produccion que necesita mas insumo del que
-- hay disponible o en camino, el sistema genera una solicitud de cotizacion
-- consolidada e invita por correo a los proveedores activos que ofrecen esos
-- insumos una vez que el gerente de compras confirma el envio (la solicitud
-- nace pendiente de confirmacion, sin enlaces). Al vencer el plazo de
-- respuesta se cierra y se generan los planes de ordenes de compra que el
-- gerente de compras revisa.
--
--   configuracion_compras        fila unica (id = 1) con el plazo de respuesta,
--                                la cantidad de planes y el criterio de orden
--   solicitud_cotizacion         solicitud de una planificacion (una sola no
--                                cancelada por planificacion), su estado y los
--                                intentos fallidos del cierre programado
--   linea_solicitud_cotizacion   insumo faltante con su calculo
--   invitacion_cotizacion        enlace de un proveedor (solo el hash SHA-256
--                                del token, nunca el token) y el resultado del
--                                envio del correo
--   oferta_cotizacion            presentacion, precio y cantidad ofrecidos
--   plan_compra                  plan generado (conjunto de ordenes propuestas)
--   orden_compra_propuesta       orden propuesta a un proveedor; se vincula a
--                                la orden de compra definitiva al confirmarla
--   item_orden_compra_propuesta  item de una orden propuesta
--
-- La bitacora de auditoria admite el concepto de la configuracion de compras.
-- =============================================================================

create table configuracion_compras (
    id bigint not null,
    plazo_respuesta_horas integer not null,
    cantidad_planes integer not null,
    criterio_plan_compra varchar(255) not null,
    peso_precio double precision not null,
    created_date timestamp(6),
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_configuracion_compras primary key (id),
    constraint ck_configuracion_compras_id check (id = 1),
    constraint ck_configuracion_compras_plazo_respuesta_horas check (plazo_respuesta_horas > 0),
    constraint ck_configuracion_compras_cantidad_planes check (cantidad_planes > 0),
    constraint ck_configuracion_compras_criterio_plan_compra check (criterio_plan_compra in ('MENOR_PRECIO','MAYOR_CANTIDAD','PONDERADO')),
    constraint ck_configuracion_compras_peso_precio check (peso_precio >= 0 and peso_precio <= 100)
);

insert into configuracion_compras (id, plazo_respuesta_horas, cantidad_planes, criterio_plan_compra, peso_precio,
                                   created_date, last_modified_date, created_by, last_modified_by)
values (1, 48, 3, 'PONDERADO', 50, current_timestamp, current_timestamp, 'SISTEMA', 'SISTEMA');

create table solicitud_cotizacion (
    id bigint generated by default as identity,
    planificacion_produccion_id bigint not null,
    estado varchar(255) not null,
    fecha_limite_respuesta timestamp(6),
    fecha_confirmacion_envio timestamp(6),
    fecha_cierre timestamp(6),
    fecha_generacion_planes timestamp(6),
    fecha_cancelacion timestamp(6),
    motivo_cancelacion varchar(255),
    intentos_cierre integer not null default 0,
    falla_cierre boolean not null default false,
    motivo_falla_cierre varchar(255),
    created_date timestamp(6),
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_solicitud_cotizacion primary key (id),
    constraint ck_solicitud_cotizacion_estado check (estado in ('PENDIENTE_DE_CONFIRMACION','ABIERTA','CERRADA','PLANES_GENERADOS','CANCELADA'))
);

create table linea_solicitud_cotizacion (
    id bigint generated by default as identity,
    solicitud_cotizacion_id bigint not null,
    insumo_id bigint not null,
    cantidad_requerida double precision not null,
    cantidad_disponible double precision not null,
    cantidad_comprometida_lotes double precision not null,
    cantidad_pendiente_recepcion double precision not null,
    cantidad_faltante double precision not null,
    sin_proveedor boolean not null,
    constraint pk_linea_solicitud_cotizacion primary key (id),
    constraint uk_linea_solicitud_cotizacion_solicitud_insumo unique (solicitud_cotizacion_id, insumo_id),
    constraint ck_linea_solicitud_cotizacion_cantidad_faltante check (cantidad_faltante > 0)
);

create table invitacion_cotizacion (
    id bigint generated by default as identity,
    solicitud_cotizacion_id bigint not null,
    proveedor_id bigint not null,
    token_hash varchar(64),
    fecha_expiracion timestamp(6),
    estado_envio varchar(255) not null,
    intentos_envio integer not null default 0,
    fecha_ultimo_intento_envio timestamp(6),
    fecha_respuesta timestamp(6),
    created_date timestamp(6),
    last_modified_date timestamp(6),
    created_by varchar(255),
    last_modified_by varchar(255),
    constraint pk_invitacion_cotizacion primary key (id),
    constraint uk_invitacion_cotizacion_token_hash unique (token_hash),
    constraint uk_invitacion_cotizacion_solicitud_proveedor unique (solicitud_cotizacion_id, proveedor_id),
    constraint ck_invitacion_cotizacion_estado_envio check (estado_envio in ('PENDIENTE','ENVIADA','FALLIDA'))
);

create table oferta_cotizacion (
    id bigint generated by default as identity,
    invitacion_cotizacion_id bigint not null,
    linea_solicitud_cotizacion_id bigint not null,
    catalogo_proveedor_id bigint not null,
    precio_unitario numeric(14,4) not null,
    cantidad_disponible integer not null,
    constraint pk_oferta_cotizacion primary key (id),
    constraint uk_oferta_cotizacion_invitacion_linea unique (invitacion_cotizacion_id, linea_solicitud_cotizacion_id),
    constraint ck_oferta_cotizacion_precio_unitario check (precio_unitario > 0),
    constraint ck_oferta_cotizacion_cantidad_disponible check (cantidad_disponible > 0)
);

create table plan_compra (
    id bigint generated by default as identity,
    solicitud_cotizacion_id bigint not null,
    numero integer not null,
    estado varchar(255) not null,
    constraint pk_plan_compra primary key (id),
    constraint uk_plan_compra_solicitud_numero unique (solicitud_cotizacion_id, numero),
    constraint ck_plan_compra_estado check (estado in ('PROPUESTO','ELEGIDO','DESCARTADO','CANCELADO'))
);

create table orden_compra_propuesta (
    id bigint generated by default as identity,
    plan_compra_id bigint not null,
    proveedor_id bigint not null,
    estado varchar(255) not null,
    orden_compra_id bigint,
    constraint pk_orden_compra_propuesta primary key (id),
    constraint uk_orden_compra_propuesta_orden_compra_id unique (orden_compra_id),
    constraint ck_orden_compra_propuesta_estado check (estado in ('PROPUESTA','CONFIRMADA','DESCARTADA'))
);

create table item_orden_compra_propuesta (
    id bigint generated by default as identity,
    orden_compra_propuesta_id bigint not null,
    linea_solicitud_cotizacion_id bigint not null,
    catalogo_proveedor_id bigint not null,
    cantidad integer not null,
    precio_unitario numeric(14,4) not null,
    constraint pk_item_orden_compra_propuesta primary key (id),
    constraint ck_item_orden_compra_propuesta_cantidad check (cantidad > 0)
);

alter table if exists solicitud_cotizacion
    add constraint fk_solicitud_cotizacion_planificacion_produccion_id foreign key (planificacion_produccion_id) references planificacion_produccion (id);

alter table if exists linea_solicitud_cotizacion
    add constraint fk_linea_solicitud_cotizacion_solicitud_cotizacion_id foreign key (solicitud_cotizacion_id) references solicitud_cotizacion (id);

alter table if exists linea_solicitud_cotizacion
    add constraint fk_linea_solicitud_cotizacion_insumo_id foreign key (insumo_id) references insumo (id);

alter table if exists invitacion_cotizacion
    add constraint fk_invitacion_cotizacion_solicitud_cotizacion_id foreign key (solicitud_cotizacion_id) references solicitud_cotizacion (id);

alter table if exists invitacion_cotizacion
    add constraint fk_invitacion_cotizacion_proveedor_id foreign key (proveedor_id) references proveedor (id);

alter table if exists oferta_cotizacion
    add constraint fk_oferta_cotizacion_invitacion_cotizacion_id foreign key (invitacion_cotizacion_id) references invitacion_cotizacion (id);

alter table if exists oferta_cotizacion
    add constraint fk_oferta_cotizacion_linea_solicitud_cotizacion_id foreign key (linea_solicitud_cotizacion_id) references linea_solicitud_cotizacion (id);

alter table if exists oferta_cotizacion
    add constraint fk_oferta_cotizacion_catalogo_proveedor_id foreign key (catalogo_proveedor_id) references catalogo_proveedor (id);

alter table if exists plan_compra
    add constraint fk_plan_compra_solicitud_cotizacion_id foreign key (solicitud_cotizacion_id) references solicitud_cotizacion (id);

alter table if exists orden_compra_propuesta
    add constraint fk_orden_compra_propuesta_plan_compra_id foreign key (plan_compra_id) references plan_compra (id);

alter table if exists orden_compra_propuesta
    add constraint fk_orden_compra_propuesta_proveedor_id foreign key (proveedor_id) references proveedor (id);

alter table if exists orden_compra_propuesta
    add constraint fk_orden_compra_propuesta_orden_compra_id foreign key (orden_compra_id) references orden_compra (id);

alter table if exists item_orden_compra_propuesta
    add constraint fk_item_orden_compra_propuesta_orden_compra_propuesta_id foreign key (orden_compra_propuesta_id) references orden_compra_propuesta (id);

alter table if exists item_orden_compra_propuesta
    add constraint fk_item_orden_compra_propuesta_linea_solicitud_cotizacion_id foreign key (linea_solicitud_cotizacion_id) references linea_solicitud_cotizacion (id);

alter table if exists item_orden_compra_propuesta
    add constraint fk_item_orden_compra_propuesta_catalogo_proveedor_id foreign key (catalogo_proveedor_id) references catalogo_proveedor (id);

-- El cierre programado busca las solicitudes abiertas vencidas; los listados filtran por planificacion
CREATE INDEX IF NOT EXISTS idx_solicitud_cotizacion_estado_fecha_limite_respuesta
    ON solicitud_cotizacion (estado, fecha_limite_respuesta);

-- Una sola solicitud no cancelada por planificacion: la generacion es idempotente
CREATE UNIQUE INDEX IF NOT EXISTS udx_solicitud_cotizacion_planificacion_vigente
    ON solicitud_cotizacion (planificacion_produccion_id) WHERE estado <> 'CANCELADA';

